import json
import os
import jdatetime
from rokh import get_events, DateSystem

START_YEAR = 1400
END_YEAR = 1430

OUT_PATH = os.path.join(os.path.dirname(__file__), "..", "assets", "events-data.js")
REGIONAL_OUT_PATH = os.path.join(os.path.dirname(__file__), "..", "assets", "events-regional.js")


def month_length(jy: int, jm: int) -> int:
    if jm <= 6:
        return 31
    if jm <= 11:
        return 30
    return 30 if jdatetime.date(jy, 1, 1).isleap() else 29


def main():
    data = {}
    regional = {}
    for jy in range(START_YEAR, END_YEAR + 1):
        for jm in range(1, 13):
            for jd in range(1, month_length(jy, jm) + 1):
                info = get_events(day=jd, month=jm, year=jy, input_date_system=DateSystem.JALALI)
                jalali_events = [e for e in info["events"]["jalali"] if e["description"] in ALLOWED_EVENTS]
                events = [RENAME.get(e["description"], e["description"]) for e in jalali_events]
                is_holiday = any(e["is_holiday"] for e in jalali_events) or any(
                    e["is_holiday"] for e in info["events"]["hijri"]
                )
                if events or is_holiday:
                    key = f"{jy:04d}-{jm:02d}-{jd:02d}"
                    data[key] = {"events": events, "is_holiday": is_holiday}

                regional_events = [RENAME.get(e["description"], e["description"]) for e in info["events"]["jalali"] if e["description"] in REGIONAL_EVENTS]
                if regional_events:
                    key = f"{jy:04d}-{jm:02d}-{jd:02d}"
                    regional[key] = regional_events

    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write("window.SARE_EVENTS = ")
        json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")
    print(f"{OUT_PATH} -> {len(data)} / {START_YEAR}-{END_YEAR}")

    with open(REGIONAL_OUT_PATH, "w", encoding="utf-8") as f:
        f.write("window.SARE_EVENTS_REGIONAL = ")
        json.dump(regional, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")
    print(f"{REGIONAL_OUT_PATH} -> {len(regional)} / {START_YEAR}-{END_YEAR}")


if __name__ == "__main__":
    main()
