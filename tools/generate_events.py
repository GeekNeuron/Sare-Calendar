def norm(s: str) -> str:
    """برای هم‌سنجیِ رشته‌ها: بی‌نیم‌فاصله، بی‌فاصله‌ی تکراری، «ك/ي» عربی یکسان."""
    s = s.replace("ك", "ک").replace("ي", "ی").replace("\u200c", "")
    return re.sub(r"\s+", " ", s).strip()


