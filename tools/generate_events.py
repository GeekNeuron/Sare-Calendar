def chaharshanbe_suri_day(jy: int) -> int:
    """شبِ سه‌شنبه‌ی پیش از آخرین چهارشنبه‌ی سال؛ با تقویمِ time.ir برای ۱۴۰۰–۱۴۱۱ سنجیده شد."""
    last = 30 if jdatetime.date(jy, 1, 1).isleap() else 29
    for d in range(last, 0, -1):
        if jdatetime.date(jy, 12, d).weekday() == 4:  # چهارشنبه
            return d - 1
    raise ValueError(jy)


def clean(desc: str) -> str:
    return RENAME.get(norm(desc), re.sub(r"\s+", " ", desc).strip())


def month_length(jy: int, jm: int) -> int:
    if jm <= 6:
        return 31
    if jm <= 11:
        return 30
    return 30 if jdatetime.date(jy, 1, 1).isleap() else 29


def write_js(path: str, var: str, data) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"window.{var} = ")
        json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")


def main():
    data = {}
    regional = {}
    for jy in range(START_YEAR, END_YEAR + 1):
        for jm in range(1, 13):
            for jd in range(1, month_length(jy, jm) + 1):
                info = get_events(day=jd, month=jm, year=jy, input_date_system=DateSystem.JALALI)
                key = f"{jy:04d}-{jm:02d}-{jd:02d}"
                kept, reg, hidden_civil = [], [], False
                for e in info["events"]["jalali"]:
                    n = norm(e["description"])
                    if n in EXCLUDED_ISLAMIC or n in EXCLUDED_TOPIC or n in DUPLICATE_OF_APP:
                        continue
                    if n in REGIME_RAW_IGNORED:
                        continue
                    if n in REGIONAL_EVENTS:
                        reg.append(clean(e["description"]))
                        continue
                    if norm(clean(e["description"])) in EXCLUDED_REGIME:
                        hidden_civil = hidden_civil or e["is_holiday"]
                        continue
                    kept.append(e)
                events = []
                for e in kept:
                    text = clean(e["description"])
                    if text not in events:
                        events.append(text)
                for t in ADDED_FIXED.get((jm, jd), []):
                    if t not in events:
                        events.append(t)
                if jm == 12 and jd == chaharshanbe_suri_day(jy):
                    events.append("چهارشنبه‌سوری (شبِ آخرین سه‌شنبه‌ی سال)")
                kept_holiday = any(e["is_holiday"] for e in kept)
                lunar = any(e["is_holiday"] for e in info["events"]["hijri"])
                is_holiday = kept_holiday or hidden_civil or lunar
                if events or is_holiday:
                    data[key] = {"events": events, "is_holiday": is_holiday}
                    if is_holiday and not kept_holiday:
                        data[key]["h"] = True  # فرویشِ بی‌نام (قمری یا از رخدادِ کنارگذاشته)
                if reg:
                    regional[key] = reg
    write_js(OUT_PATH, "SARE_EVENTS", data)
    print(f"{OUT_PATH} -> {len(data)} days")
    write_js(REGIONAL_OUT_PATH, "SARE_EVENTS_REGIONAL", regional)
